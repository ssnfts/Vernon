//! Text of the generated post-processing script. All slicer-specific text of the script
//! bridge lives here.
//!
//! Interface used: the post-processing script setting that the Slic3r family of slicers
//! share (the setting `post_process`; public description: PrusaSlicer knowledge base,
//! "Output options" / "Post-processing scripts", and the OrcaSlicer wiki page on the same
//! setting). A script is started once per exported G-code file with the path of that
//! file as its only argument; it edits the file in place and a non-zero exit code makes
//! the export fail. Nothing else of the slicer is used, so the script needs only a
//! Python 3 interpreter and the standard library.
//!
//! KNOWN: the request/result protocol is defined by `script_bridge.rs`, not by a slicer.
//! The script and the Rust reference function `script_bridge::apply_to_gcode` implement
//! the same rules; a test runs both on the same G-code and compares them.

/// Protocol version written into and expected from request and result files.
pub const PROTOCOL_VERSION: u32 = 2;
/// Comment line that starts every layer in the G-code of the slicers this targets.
pub const LAYER_MARKER: &str = ";LAYER_CHANGE";
/// Prefix of the comment the script leaves at the end of a processed file.
pub const DONE_PREFIX: &str = "; vernon_post_process:";

/// Render the script. `request_path` and `result_path` are embedded as string literals.
pub fn render(request_path: &str, result_path: &str) -> String {
    let lit = |s: &str| serde_json::to_string(s).expect("string always serialises");
    format!(
        r#"# Generated by Vernon. Post-processing script: the slicer starts it with the path of
# an exported G-code file as its only argument. It inserts G-code lines at the start of
# the requested layers, edits the file in place and writes a result file.
# Standard library only.
import json
import os
import sys

REQUEST = {req}
RESULT = {res}
MARKER = {marker}
DONE = {done}
VERSION = {ver}


def main():
    if len(sys.argv) != 2:
        sys.stderr.write("usage: script <gcode file>\n")
        return 2
    path = sys.argv[1]
    with open(REQUEST, "r", encoding="utf-8") as f:
        request = json.load(f)
    if request.get("version") != VERSION:
        sys.stderr.write("unsupported request version\n")
        return 2
    insertions = request["insertions"]
    with open(path, "r", encoding="utf-8", errors="surrogateescape", newline="") as f:
        text = f.read()
    lines = text.split("\n")
    eol = "\r" if lines and lines[0].endswith("\r") else ""
    results = []
    if any(line.strip().startswith(DONE) for line in lines):
        for index in range(len(insertions)):
            results.append({{"index": index, "status": "failed", "message": "file was already processed"}})
        out = lines
    else:
        positions = [i for i, line in enumerate(lines) if line.strip() == MARKER]
        before = {{}}
        for index, ins in enumerate(insertions):
            layer = ins["layer"]
            if layer < 1 or layer > len(positions):
                message = "layer %d not found (file has %d layers)" % (layer, len(positions))
                results.append({{"index": index, "status": "failed", "message": message}})
            else:
                before.setdefault(positions[layer - 1], []).append(index)
                results.append({{"index": index, "status": "applied", "message": ""}})
        out = []
        for i, line in enumerate(lines):
            for index in before.get(i, []):
                ins = insertions[index]
                out.append("; vernon: inserted before layer %d%s" % (ins["layer"], eol))
                for g in ins["gcode"].split("\n"):
                    out.append(g + eol)
            out.append(line)
        applied = sum(1 for r in results if r["status"] == "applied")
        summary = "%s applied=%d failed=%d" % (DONE, applied, len(results) - applied)
        if out and out[-1] == "":
            out.insert(len(out) - 1, summary + eol)
        else:
            out.append(summary)
    if out is not lines:
        tmp = path + ".vernon.tmp"
        with open(tmp, "w", encoding="utf-8", errors="surrogateescape", newline="") as f:
            f.write("\n".join(out))
        os.replace(tmp, path)
    with open(RESULT, "w", encoding="utf-8") as f:
        json.dump({{"version": VERSION, "results": results}}, f)
    return 0


sys.exit(main())
"#,
        req = lit(request_path),
        res = lit(result_path),
        marker = lit(LAYER_MARKER),
        done = lit(DONE_PREFIX),
        ver = PROTOCOL_VERSION,
    )
}
