//! All slicer-specific text of the script bridge lives here so it is easy to correct.
//!
//! KNOWN: the bridge protocol itself (a JSON request file in, a JSON result file out,
//! both versioned) is defined by `script_bridge.rs`, not by any slicer.
//!
//! UNVERIFIED (guesses about the slicer plug-in API, which is an unstable alpha):
//! * that the plug-in language is Python 3 and the host runs a script file given on
//!   its command line;
//! * the name `slicer_host` of the module the host injects and its two entry points
//!   `add_connector(kind, position, normal, diameter, depth) -> bool` and
//!   `last_error() -> str`.
//!
//! If any of these is wrong, change only `HOST_MODULE`, `HOST_CALL` and `HOST_ERROR`
//! below; the rest of the script and the Rust side do not depend on them.

/// Name of the module the host is assumed to provide (UNVERIFIED).
pub const HOST_MODULE: &str = "slicer_host";
/// Host call that places one connector (UNVERIFIED).
pub const HOST_CALL: &str = "add_connector";
/// Host call that returns the text of the last failure (UNVERIFIED).
pub const HOST_ERROR: &str = "last_error";
/// Protocol version written into and expected from the result file.
pub const PROTOCOL_VERSION: u32 = 1;

/// Render the script. `request_path` and `result_path` are embedded as string literals.
pub fn render(request_path: &str, result_path: &str) -> String {
    let lit = |s: &str| serde_json::to_string(s).expect("string always serialises");
    format!(
        r#"# Generated by Vernon. Reads a connector request and writes a result file.
import json
import {module} as host

REQUEST = {req}
RESULT = {res}


def main():
    with open(REQUEST, "r", encoding="utf-8") as f:
        request = json.load(f)
    results = []
    for index, c in enumerate(request["connectors"]):
        try:
            ok = bool(host.{call}(c["kind"], c["position"], c["normal"], c["diameter_mm"], c["depth_mm"]))
            message = "" if ok else str(host.{err}())
        except Exception as exc:  # report, never abort the whole batch
            ok, message = False, str(exc)
        results.append({{"index": index, "status": "applied" if ok else "failed", "message": message}})
    with open(RESULT, "w", encoding="utf-8") as f:
        json.dump({{"version": {ver}, "results": results}}, f)


main()
"#,
        module = HOST_MODULE,
        call = HOST_CALL,
        err = HOST_ERROR,
        ver = PROTOCOL_VERSION,
        req = lit(request_path),
        res = lit(result_path),
    )
}
