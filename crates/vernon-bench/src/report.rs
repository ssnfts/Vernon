//! `REPORT.md` and `results.json`.

use std::fmt::Write as _;
use std::path::Path;

use serde_json::json;

use crate::harness::{Case, Status};

pub fn write(dir: &Path, cases: &[Case]) -> std::io::Result<()> {
    std::fs::create_dir_all(dir)?;
    let count = |w: &str| cases.iter().filter(|c| c.status.word() == w).count();
    let (p, f, s) = (count("PASS"), count("FAIL"), count("SKIPPED"));
    let host = format!("{} {}, {} logical CPUs", std::env::consts::OS, std::env::consts::ARCH, std::thread::available_parallelism().map(|n| n.get()).unwrap_or(0));
    let doc = json!({
        "summary": {"pass": p, "fail": f, "skipped": s, "total": cases.len()},
        "host": host,
        "vernon_version": env!("CARGO_PKG_VERSION"),
        "cases": cases.iter().map(Case::to_json).collect::<Vec<_>>(),
    });
    std::fs::write(dir.join("results.json"), serde_json::to_string_pretty(&doc).unwrap_or_default())?;

    let mut m = String::new();
    let _ = writeln!(m, "# Vernon validation report\n");
    let _ = writeln!(m, "Generated by `bench/run.ps1` (or `bench/run.sh`). Host: {host}.\n");
    let _ = writeln!(m, "**{p} PASS, {f} FAIL, {s} SKIPPED** of {} checks. Machine-readable copy: `results.json`.", cases.len());
    let _ = writeln!(m, "\nStatuses are only PASS, FAIL and SKIPPED(reason). A reference is either an analytic result, a published figure with its source, or the measured output of a tool run on this machine. See `docs/VALIDATION.md` for what is not validated.\n");

    let fails: Vec<&Case> = cases.iter().filter(|c| matches!(c.status, Status::Fail(_))).collect();
    if !fails.is_empty() {
        let _ = writeln!(m, "## Failures\n");
        for c in fails {
            let _ = writeln!(m, "- **{}** {}: {}", c.id, c.title, c.status.detail());
        }
        let _ = writeln!(m);
    }
    for (tier, title) in [("A", "Tier A: analytic and textbook references"), ("B", "Tier B: open-source reference tools"), ("C", "Tier C: golden slots for licensed tools (owner records)"), ("E", "End to end"), ("P", "Performance")] {
        let rows: Vec<&Case> = cases.iter().filter(|c| c.tier == tier).collect();
        if rows.is_empty() {
            continue;
        }
        let _ = writeln!(m, "## {title}\n");
        if tier == "P" {
            let _ = writeln!(m, "Targets (stated before measuring), wall seconds for 10k / 100k / 1M triangles:\n\n{}", crate::perf::targets_table());
            let _ = writeln!(m, "| Case | Status | Detail | Wall time |\n|---|---|---|---|");
        } else {
            let _ = writeln!(m, "| Check | Status | Detail |\n|---|---|---|");
        }
        for c in rows {
            let detail = if c.status.detail().is_empty() { c.notes.join("; ") } else { c.status.detail().to_string() };
            let detail = detail.replace('|', "/");
            if tier == "P" {
                let _ = writeln!(m, "| {} | {} | {} | {:.1} s |", c.id, c.status.word(), detail, c.ms / 1e3);
            } else {
                let _ = writeln!(m, "| {} {} | {} | {} |", c.id, c.title, c.status.word(), detail);
            }
        }
        let _ = writeln!(m);
    }
    let _ = writeln!(m, "## Comparisons\n\n| Check | Quantity | Vernon | Reference | Tolerance | OK |\n|---|---|---|---|---|---|");
    for c in cases.iter().filter(|c| c.tier != "P") {
        for x in &c.cmps {
            let _ = writeln!(m, "| {} | {} | {:.6} {} | {:.6} | {} | {} |", c.id, x.name.replace('|', "/"), x.measured, x.unit, x.reference, x.tolerance, if x.ok { "yes" } else { "**no**" });
        }
    }
    let _ = writeln!(m, "\n## References\n");
    for c in cases {
        let _ = writeln!(m, "- {}: {}", c.id, c.reference);
    }
    std::fs::write(dir.join("REPORT.md"), m)
}
