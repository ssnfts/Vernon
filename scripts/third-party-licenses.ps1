# Regenerates THIRD_PARTY_LICENSES.md: every crates.io crate the workspace
# links for the host target, its declared licence, and the licence files the
# crate ships (texts identical up to white space are printed once, with the crates using them).
#
#   . .\scripts\dev-env.ps1; .\scripts\third-party-licenses.ps1
#
# Run it after changing dependencies. It reads only cargo's local registry
# cache, so build once first (the sources must have been downloaded).
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$cargoHome = if ($env:CARGO_HOME) { $env:CARGO_HOME } else { Join-Path $env:USERPROFILE '.cargo' }
$srcDirs = Get-ChildItem (Join-Path $cargoHome 'registry\src') -Directory

$lines = cargo tree --workspace -e normal --prefix none --format '{p}|{l}' --manifest-path (Join-Path $root 'Cargo.toml')
if ($LASTEXITCODE -ne 0) { throw 'cargo tree failed' }
$crates = $lines | ForEach-Object { $_ -replace ' \(\*\)$', '' } | Where-Object { $_ -and $_ -notmatch '\(' } | Sort-Object -Unique

$texts = [ordered]@{}   # hash -> @{ file; text; users }
$rows = New-Object System.Collections.Generic.List[string]
$missing = New-Object System.Collections.Generic.List[string]
foreach ($c in $crates) {
    $pkg, $lic = $c -split '\|', 2
    $name, $ver = $pkg -split ' v', 2
    $rows.Add("| $name | $ver | $lic |")
    $dir = $srcDirs | ForEach-Object { Join-Path $_.FullName "$name-$ver" } | Where-Object { Test-Path $_ } | Select-Object -First 1
    $files = @()
    if ($dir) {
        $files += Get-ChildItem $dir -File | Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE)' }
        $fonts = Join-Path $dir 'fonts'
        if (Test-Path $fonts) { $files += Get-ChildItem $fonts -File -Filter '*.txt' }
    }
    if ($files.Count -eq 0) { $missing.Add("$name $ver ($lic)"); continue }
    foreach ($f in $files) {
        $text = ([IO.File]::ReadAllText($f.FullName)) -replace "`r`n", "`n"
        $h = (Get-FileHash -InputStream ([IO.MemoryStream]::new([Text.Encoding]::UTF8.GetBytes(($text -replace '\s+', ' ').Trim())))).Hash
        if (-not $texts.Contains($h)) { $texts[$h] = @{ file = $f.Name; text = $text.TrimEnd(); users = New-Object System.Collections.Generic.List[string] } }
        $texts[$h].users.Add("$name $ver")
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Third-party licences')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Generated by `scripts/third-party-licenses.ps1`; do not edit by hand.')
[void]$sb.AppendLine('Vernon itself is Apache-2.0 (see `LICENSE` and `NOTICE`). Binaries built from')
[void]$sb.AppendLine('this workspace link the crates below; their licence texts follow. The fonts')
[void]$sb.AppendLine('embedded by the user interface come from `epaint_default_fonts` (OFL-1.1,')
[void]$sb.AppendLine('Ubuntu Font Licence 1.0 and the MIT-licensed emoji icon font).')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('## Crates')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| Crate | Version | Licence |')
[void]$sb.AppendLine('|---|---|---|')
foreach ($r in $rows) { [void]$sb.AppendLine($r) }
if ($missing.Count -gt 0) {
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('Crates that ship no licence file of their own (their declared licence applies; the standard texts are in the sections below):')
    [void]$sb.AppendLine('')
    foreach ($m in $missing) { [void]$sb.AppendLine("- $m") }
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('## Licence texts')
foreach ($k in $texts.Keys) {
    $t = $texts[$k]
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("### $($t.file)")
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("Used by: $($t.users -join ', ')")
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('````text')
    [void]$sb.AppendLine($t.text)
    [void]$sb.AppendLine('````')
}
$out = Join-Path $root 'THIRD_PARTY_LICENSES.md'
[IO.File]::WriteAllText($out, ($sb.ToString() -replace "`r`n", "`n"), (New-Object Text.UTF8Encoding $false))
"wrote $out ($($rows.Count) crates, $($texts.Count) distinct licence texts, $($missing.Count) without a licence file)"
